// The bundles layer and the guard generator of this family (modules/vscode
// PROP-003 ##VSCODE-BUNDLED-EXTENSION, PROP-008 ##GEN-BUNDLE). The engine
// provisions the unit and never sees what a VSIX is; what is proved here is
// the shape the type answers: the manifest and its list, the entry upstream's
// build takes, the cache it reads, the identity of a VSIX, and the guard test.

import { describe, expect, it } from 'vitest';
import { bundleGuard } from '../src/generators.ts';
import { CAPABILITIES } from '../src/index.ts';
import { BUILT_IN_EXTENSIONS_CACHE, BUNDLE_NAME_PATTERN, bundles, layers, PRODUCT_JSON_TARGET } from '../src/layers.ts';

const UNIT = { name: 'acme.pack', version: '1.2.3', sha256: 'a'.repeat(64) };

describe('the bundles layer', () => {
	it('is answered, with the capability, over product.json and builtInExtensions', () => {
		expect(CAPABILITIES).toContain('bundles');
		expect(layers.bundles).toBe(bundles);
		expect(bundles.manifestTarget).toBe(PRODUCT_JSON_TARGET);
		expect(bundles.listPath).toEqual(['builtInExtensions']);
		expect(bundles.archiveWord).toBe('VSIX');
	});

	it('reads the entries that carry a name, a version and a hash, and skips the rest', () => {
		expect(
			bundles.entries({
				builtInExtensions: [
					{ name: 'ms-vscode.js-debug', version: '1.0.0', sha256: 'b'.repeat(64), repo: 'https://example.invalid/js-debug' },
					{ name: 'no-hash', version: '1.0.0' },
					'text',
					null
				]
			})
		).toEqual([{ name: 'ms-vscode.js-debug', version: '1.0.0', sha256: 'b'.repeat(64) }]);
		expect(bundles.entries({})).toEqual([]);
		expect(bundles.entries({ builtInExtensions: 'none' })).toEqual([]);
	});

	it("writes the entry upstream's build takes, with an empty repo, and names the cache the build reads", () => {
		expect(bundles.entry(UNIT)).toEqual({ name: 'acme.pack', version: '1.2.3', sha256: 'a'.repeat(64), repo: '' });
		expect(bundles.cachePath('acme.pack')).toBe(`${BUILT_IN_EXTENSIONS_CACHE}/acme.pack`);
		expect(BUILT_IN_EXTENSIONS_CACHE).toBe('.build/builtInExtensions');
		expect(bundles.archiveRoot).toBe('extension/');
		expect(bundles.archiveManifest).toBe('extension/package.json');
	});

	it('reads the identity of a VSIX as publisher.name and version, or nothing', () => {
		expect(bundles.identity('{ "publisher": "acme", "name": "pack", "version": "1.2.3" }')).toEqual({
			name: 'acme.pack',
			version: '1.2.3'
		});
		expect(bundles.identity('{ "name": "pack", "version": "1.2.3" }')).toBeNull();
		expect(bundles.identity('{ "publisher": "", "name": "pack", "version": "1.2.3" }')).toBeNull();
		expect(bundles.identity('{ "publisher": "acme", "name": "pack" }')).toBeNull();
		expect(bundles.identity('not json')).toBeNull();
		expect(bundles.identity('[]')).toBeNull();
	});

	it('accepts a marketplace identity as a name and refuses anything else', () => {
		expect(bundles.namePattern).toBe(BUNDLE_NAME_PATTERN);
		for (const name of ['acme.pack', 'ms-vscode.js-debug', 'Publisher.Name', 'a1.b2']) expect(BUNDLE_NAME_PATTERN.test(name)).toBe(true);
		for (const name of ['pack', 'acme.', '.pack', 'acme/pack', 'acme.pack/../x', 'acme pack', 'acme..pack']) {
			expect(BUNDLE_NAME_PATTERN.test(name)).toBe(false);
		}
	});
});

describe('the guard of a bundle record', () => {
	const module = bundleGuard({ id: 'CK-product-910', unit: UNIT, ownRoot: 'src/vs/patchset', manifestTarget: 'product.json' });

	it('is a suite of the node layer under the own root, named after the unit', () => {
		expect(module.path).toBe('delta/own/test/node/bundles/acme.pack.test.ts');
		expect(module.role).toBe('test');
		expect(module.text).toContain("suite('CK-product-910', () => {");
		expect(module.text).toContain('ensureNoDisposablesAreLeakedInTestSuite();');
		expect(module.text.startsWith('// Generated by `codkit bundles add`; `codkit bundles update` rewrites it')).toBe(true);
	});

	it('reads product.json from the tree root and asserts the version and the hash of the entry', () => {
		expect(module.text).toContain("join(FileAccess.asFileUri('').fsPath, '..', ...[\"product.json\"])");
		expect(module.text).toContain("candidate.name === 'acme.pack'");
		expect(module.text).toContain("assert.strictEqual(entry.version, '1.2.3');");
		expect(module.text).toContain(`assert.strictEqual(entry.sha256, '${'a'.repeat(64)}');`);
	});

	it('counts its specifiers from the materialized location of the own root', () => {
		expect(module.text).toContain("import { FileAccess } from '../../../../base/common/network.js';");
		expect(module.text).toContain("import { ensureNoDisposablesAreLeakedInTestSuite } from '../../../../base/test/common/utils.js';");
		const deeper = bundleGuard({ id: 'CK-product-910', unit: UNIT, ownRoot: 'src/vs/acme/patchset', manifestTarget: 'product.json' });
		expect(deeper.text).toContain("import { FileAccess } from '../../../../../base/common/network.js';");
	});
});

#!/usr/bin/env node

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.slice(2).includes('--check');
const unexpected = process.argv.slice(2).filter((arg) => arg !== '--check');
if (unexpected.length > 0) {
	process.stderr.write(`unknown argument: ${unexpected[0]}\n`);
	process.exit(2);
}

const agentNames = ['ck-upstream-scout.md', 'ck-conflict-resolver.md', 'ck-verifier.md', 'ck-upgrade-reviewer.md', 'ck-cause-finder.md'];
const failures = [];

for (const name of agentNames) {
	const source = join(root, 'docs', 'codkit', 'agents', name);
	const target = join(root, '.claude', 'agents', name);
	syncExact(source, target, `agent copy ${name}`);
}

const begin = '<!-- codkit-agent-core:begin -->';
const end = '<!-- codkit-agent-core:end -->';
const core = readRequired(join(root, 'docs', 'codkit', 'agents', 'shared-core.md'));
const block = `${begin}\n<!-- Generated by tools/sync-codkit-agents.mjs; edit docs/codkit/agents/shared-core.md. -->\n${core.trimEnd()}\n${end}`;

for (const name of ['CLAUDE.md', 'AGENTS.md']) {
	const path = join(root, name);
	const current = readRequired(path);
	const next = replaceManagedBlock(current, block, name);
	writeIfNeeded(path, current, next, `generated core in ${name}`);
}

if (failures.length > 0) {
	for (const failure of failures) process.stderr.write(`${failure}\n`);
	process.exit(1);
}
process.stdout.write(check ? 'agent protocol sync check: ok\n' : 'agent protocol sync: ok\n');

function syncExact(source, target, label) {
	const wanted = readRequired(source);
	const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
	if (current === wanted) return;
	if (check) {
		failures.push(`out of sync: ${label}`);
		return;
	}
	mkdirSync(dirname(target), { recursive: true });
	writeFileSync(target, wanted, 'utf8');
}

function replaceManagedBlock(current, block, name) {
	const first = current.indexOf(begin);
	const last = current.indexOf(end);
	if ((first === -1) !== (last === -1) || (first !== -1 && current.indexOf(begin, first + begin.length) !== -1)) {
		throw new Error(`malformed managed agent core in ${name}`);
	}
	if (first === -1) return `${current.trimEnd()}\n\n${block}\n`;
	if (last < first) throw new Error(`malformed managed agent core in ${name}`);
	const after = last + end.length;
	return `${current.slice(0, first)}${block}${current.slice(after)}`;
}

function writeIfNeeded(path, current, next, label) {
	if (current === next) return;
	if (check) {
		failures.push(`out of sync: ${label}`);
		return;
	}
	writeFileSync(path, next, 'utf8');
}

function readRequired(path) {
	if (!existsSync(path)) throw new Error(`missing source: ${path}`);
	const value = readFileSync(path, 'utf8');
	if (value.includes('\r')) throw new Error(`CR is forbidden: ${path}`);
	if (!value.endsWith('\n')) throw new Error(`final LF required: ${path}`);
	return value;
}
